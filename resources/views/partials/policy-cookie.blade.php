<h3>2. Что такое файлы cookie</h3>
<p>
    Файлы cookie — это небольшие текстовые файлы, которые сохраняются в браузере посетителя
    при использовании Сайта. Они позволяют Сайту узнавать браузер посетителя, запоминать
    его настройки и собирать статистику посещений.
</p>

<h3>3. Какие файлы cookie мы используем</h3>
<p>Сайт использует следующие категории файлов cookie:</p>
<ul>
    <li>
        <strong>обязательные (технические)</strong> — необходимы для работы Сайта,
        запоминания настроек и сессии посетителя; без них Сайт не функционирует;
    </li>
    <li>
        <strong>аналитические</strong> — помогают понять, как посетители пользуются Сайтом,
        и улучшать его работу (например, при использовании сервисов веб-аналитики).
    </li>
</ul>

